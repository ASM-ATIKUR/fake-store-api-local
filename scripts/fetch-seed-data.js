// Rebuilds data/seed-data.json from the live fakestoreapi.com.
//
// This is the ONLY thing here that touches the network. `npm run seed` reads the
// committed JSON, so seeding and `npm test` work offline and always produce the
// same database. Re-run this by hand (`npm run seed:fetch`) when you want to
// refresh the fixture, and commit the result.
//
// What it keeps, deliberately narrower than upstream:
//   - every product
//   - two users: 'admin' and 'customer', both with the password '123'
//   - one cart, belonging to the customer
const fs = require('fs');
const path = require('path');

const API = 'https://fakestoreapi.com';
const OUT = path.join(__dirname, '..', 'data', 'seed-data.json');

// The two seeded accounts. Their profile (name, email, address, phone) comes from
// upstream, but the credentials and role are set here rather than inherited.
//
// That is deliberate: fakestoreapi serves two different datasets - the same people
// under the same ids, but usernames/passwords that differ between them. Picking by
// id and stamping the login ourselves makes the fixture identical whichever one we
// happen to get. Change a value here and __test__/helpers/login.js must match.
const SEED_USERS = [
	{ upstreamId: 1, username: 'admin', password: '123', role: 'admin' },
	{ upstreamId: 3, username: 'customer', password: '123', role: 'customer' },
];

async function fetchJson(route) {
	const res = await fetch(`${API}${route}`);
	if (!res.ok) {
		throw new Error(`GET ${route} failed with status ${res.status}`);
	}
	return res.json();
}

// upstream sends back mongo-ish noise the schemas don't declare
const stripUpstream = ({ _id, __v, ...rest }) => rest;

async function build() {
	console.log('fetching products...');
	const products = (await fetchJson('/products')).map(stripUpstream);
	if (!products.length) {
		throw new Error('upstream returned no products');
	}
	// model/product.js requires all three; the alternate upstream dataset shapes
	// products differently, so catch that here rather than at insertMany
	const malformed = products.find(
		(product) => product.id == null || !product.title || typeof product.price !== 'number'
	);
	if (malformed) {
		throw new Error(
			`upstream product is missing id/title/price: ${JSON.stringify(malformed).slice(0, 200)}`
		);
	}

	console.log('fetching users...');
	const allUsers = await fetchJson('/users');
	const users = SEED_USERS.map(({ upstreamId, username, password, role }) => {
		const upstream = allUsers.find((candidate) => candidate.id === upstreamId);
		if (!upstream) {
			throw new Error(`upstream has no user with id ${upstreamId}; cannot build seed data`);
		}
		if (!upstream.email || !upstream.name || !upstream.name.firstname) {
			throw new Error(
				`upstream user ${upstreamId} is missing the email/name model/user.js requires: ` +
					JSON.stringify(upstream).slice(0, 200)
			);
		}
		// profile from upstream, identity from us. active is what model/user.js
		// defaults to, written out so the fixture shows the whole shape.
		return { ...stripUpstream(upstream), username, password, role, active: true };
	});

	const customer = users.find((user) => user.role === 'customer');

	console.log('fetching carts...');
	const allCarts = await fetchJson('/carts');
	// Upstream has carts for several users, most of whom we no longer seed. Keep
	// one, and make sure it is the customer's: cart writes are customer-only, so
	// a cart belonging to the admin would be unreachable by every route.
	const source =
		allCarts.find((cart) => cart.userId === customer.id && cart.products.length) ||
		allCarts.find((cart) => cart.products.length);
	if (!source) {
		throw new Error('upstream returned no cart with any products');
	}

	const priceOf = new Map(products.map((product) => [product.id, product.price]));
	const cart = {
		id: 1,
		userId: customer.id,
		date: source.date,
		// priceAtAdd is what the API stamps on every line it writes itself.
		// Upstream cart lines carry no price, so take it from the catalog and the
		// seeded cart looks like one a shopper actually filled.
		products: source.products
			.filter((line) => priceOf.has(line.productId))
			.map((line) => ({
				productId: line.productId,
				quantity: line.quantity,
				priceAtAdd: priceOf.get(line.productId),
			})),
	};

	return {
		_comment: `generated by scripts/fetch-seed-data.js from ${API} — run 'npm run seed:fetch' to refresh`,
		generatedAt: new Date().toISOString(),
		products,
		users,
		carts: [cart],
	};
}

build()
	.then((data) => {
		fs.mkdirSync(path.dirname(OUT), { recursive: true });
		fs.writeFileSync(OUT, `${JSON.stringify(data, null, 2)}\n`);
		console.log(
			`wrote ${path.relative(process.cwd(), OUT)}: ` +
				`products=${data.products.length} users=${data.users.length} carts=${data.carts.length}`
		);
		process.exit(0);
	})
	.catch((err) => {
		console.error(err);
		process.exit(1);
	});
